(()=>{'use strict';
  const dialog=document.getElementById('password-dialog');
  if(!dialog)return;
  const form=dialog.querySelector('[data-password-form]');
  const password=dialog.querySelector('[data-password-new]');
  const confirmation=dialog.querySelector('[data-password-confirm]');
  const meter=dialog.querySelector('[data-password-strength-meter]');
  const strengthLabel=dialog.querySelector('[data-password-strength-label]');
  const hint=dialog.querySelector('[data-password-strength-hint]');
  const match=dialog.querySelector('[data-password-match]');
  const levels=['Digite uma senha','Muito fraca','Fraca','Razoável','Forte'];
  const messages=['Use uma senha longa, única e difícil de adivinhar.','Evite combinações comuns e aumente o comprimento.','Tente usar mais palavras ou caracteres.','Boa base! Uma senha maior oferece mais proteção.','Boa senha estimada. Evite reutilizá-la em outros serviços.'];
  const score=value=>{
    if(!value)return 0;
    const normalized=value.toLowerCase();
    const common=/(password|senha|123456|qwerty|admin|tuffer|abcdef|111111|000000)/i.test(value);
    const classes=[/[a-z]/.test(value),/[A-Z]/.test(value),/[0-9]/.test(value),/[^a-zA-Z0-9]/.test(value)].filter(Boolean).length;
    let result=1;
    if(value.length>=10)result++;
    if(value.length>=14)result++;
    if(value.length>=18||classes>=3)result++;
    if(value.length<8||common)result=Math.min(result,1);
    if(value.length<12)result=Math.min(result,2);
    return Math.min(4,result);
  };
  const refresh=()=>{
    const level=score(password.value);
    meter.dataset.level=String(level);
    meter.setAttribute('aria-valuenow',String(level));
    strengthLabel.textContent=levels[level];
    hint.textContent=messages[level];
    const entered=confirmation.value.length>0;
    const matches=password.value===confirmation.value;
    match.textContent=entered?(matches?'As senhas coincidem.':'As senhas não coincidem.'):'';
    match.dataset.match=entered?(matches?'yes':'no'):'';
    confirmation.setCustomValidity(entered&&!matches?'As senhas não coincidem.':'');
  };
  password.addEventListener('input',refresh);
  confirmation.addEventListener('input',refresh);
  dialog.querySelectorAll('[data-password-visibility]').forEach(button=>button.addEventListener('click',()=>{
    const field=button.parentElement.querySelector('input');
    const visible=field.type==='password';
    field.type=visible?'text':'password';
    button.setAttribute('aria-pressed',String(visible));
    button.setAttribute('aria-label',(visible?'Ocultar':'Mostrar')+' '+(field.name==='current_password'?'senha atual':field.name==='password'?'nova senha':'confirmação de senha'));
    button.classList.toggle('is-visible',visible);
    field.focus({preventScroll:true});
  }));
  const open=()=>{
    document.querySelector('.user-dropdown[open]')?.removeAttribute('open');
    if(!dialog.open)dialog.showModal();
    dialog.querySelector('input[name="current_password"]').focus();
  };
  const close=()=>{if(dialog.open)dialog.close();form.reset();dialog.querySelectorAll('[data-password-visibility]').forEach(button=>{button.classList.remove('is-visible');button.setAttribute('aria-pressed','false');const input=button.parentElement.querySelector('input');input.type='password'});confirmation.setCustomValidity('');refresh()};
  document.querySelectorAll('[data-password-modal-open]').forEach(link=>link.addEventListener('click',event=>{event.preventDefault();open()}));
  dialog.querySelectorAll('[data-password-modal-close]').forEach(button=>button.addEventListener('click',close));
  dialog.addEventListener('click',event=>{if(event.target===dialog)close()});
  dialog.addEventListener('close',()=>{form.reset();refresh()});
  form.addEventListener('submit',event=>{refresh();if(!form.checkValidity()){event.preventDefault();form.reportValidity()}});
  if(new URLSearchParams(location.search).has('alterar-senha'))open();
  refresh();
})();
